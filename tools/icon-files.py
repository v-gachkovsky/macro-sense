#!/usr/bin/env python3
"""Writes MacroSense/IconFiles.lua: the names of the game's icon files (Interface/Icons) by file ID, so the icon
search finds "book" in INV_Misc_Book_09 as Wowhead does. The game has no names for its icons; they come from the
community's list of WoW's file names, github.com/wowdev/wow-listfile. Run it after a game patch, from the repo:

    python3 tools/icon-files.py              downloads the list's interface part
    python3 tools/icon-files.py interface.csv    or reads a copy of it ("file ID;path" lines)
"""
import pathlib
import sys
import urllib.request

URL = "https://raw.githubusercontent.com/wowdev/wow-listfile/master/parts/interface.csv"
OUT = pathlib.Path(__file__).resolve().parent.parent / "MacroSense" / "IconFiles.lua"
PREFIX, EXT = "interface/icons/", ".blp"


def rows(text):
    """(file ID, name) of each icon: "133741;Interface/ICONS/INV_Misc_Book_09.blp" -> (133741, "inv_misc_book_09")."""
    for line in text.splitlines():
        fid, _, path = line.partition(";")
        path = path.strip().lower()
        if fid.isdigit() and path.startswith(PREFIX) and path.endswith(EXT):
            name = path[len(PREFIX):-len(EXT)]
            if name and "/" not in name and "]" not in name:
                yield int(fid), name


def main():
    if len(sys.argv) > 1:
        text = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8", errors="replace")
    else:
        with urllib.request.urlopen(URL) as response:
            text = response.read().decode("utf-8", errors="replace")
    icons = sorted(dict(rows(text)).items())
    body = "\n".join(f"{fid} {name}" for fid, name in icons)
    OUT.write_text(
        "-- Generated by tools/icon-files.py: don't edit it, run that after a game patch. The names of the game's icon\n"
        "-- files (Interface\\Icons) by file ID, from the community's list of WoW's file names\n"
        "-- (github.com/wowdev/wow-listfile): the game has none for its icons. The icon search reads them\n"
        "-- (IconNames.File).\n"
        "local _, ns = ...\n"
        "ns = ns or {}\n"
        f"ns.ICON_FILES = [[\n{body}\n]]\n",
        encoding="utf-8",
    )
    print(f"{len(icons)} icons, {OUT.stat().st_size} bytes: {OUT}")


if __name__ == "__main__":
    main()
